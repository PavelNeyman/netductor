func T(key string, args ...any) string {
	lang := Lang()
	s, ok := dict[lang][key]
	if !ok { s, ok = dict["en"][key] }
	if !ok { s = key }
	if len(args) == 0 { return s }
	return fmt.Sprintf(s, args...)
}

func Register(lang, key, value string) {
	if dict[lang] == nil { dict[lang] = map[string]string{} }
	dict[lang][key] = value
}
